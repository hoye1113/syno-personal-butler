import test from "node:test";
import assert from "node:assert/strict";
import { promises as fs } from "node:fs";
import os from "node:os";
import path from "node:path";
import { executeDomainOperation } from "../packages/syno-core/domain-operations.mjs";
import { MemoryStore, recallMemories } from "../packages/syno-core/memory-store.mjs";
import { recordVersion, listDomainRecords } from "../packages/syno-core/domain-records.mjs";
const item = (id, extra = {}) => { const record = { schemaVersion: 2, id, ownerKey: "owner", status: "active", statement: "回答先给中文实例", kind: "preference", scope: "global", triggers: [], sourceMessageId: "s", confirmationMessageId: "c", ...extra }; return { record, version: recordVersion(record) }; };
test("deterministic recall: global rules, topic triggers, background and inactive records", () => {
  const memories = [item("global"), item("background", { kind: "background", statement: "从事游戏开发", triggers: ["游戏引擎"] }), item("topic", { scope: "写作", triggers: ["写作结构", "outline"], statement: "写作先列大纲" }), item("rejected", { status: "rejected" }), item("test", { testData: true }), item("sensitive", { sensitive: true }), item("old", { status: "active" }), item("new", { supersedes: "old", statement: "以后给英文实例" })];
  assert.deepEqual(recallMemories(memories, "写作结构怎么组织").map(r => r.id), ["topic", "global", "new"]);
  assert.deepEqual(recallMemories([memories[1]], "今天下雨吗"), []);
  assert.equal(recallMemories([memories[1]], "游戏引擎哪个好")[0].id, "background");
  assert.deepEqual(recallMemories([memories[2]], "写作"), []);
  assert.deepEqual(recallMemories([item("plain-background", { kind: "background", scope: "global", triggers: [] })], "今天天气"), [], "漏填字段的 background 不能全局召回");
});
test("recall enforces whole-record budget and stable ties", () => {
  const items = Array.from({ length: 10 }, (_, n) => item(`r${n}`));
  assert.deepEqual(recallMemories(items.reverse(), "问题").map(r => r.id), ["r0", "r1", "r2", "r3", "r4"]);
  assert.equal(recallMemories(items, "问题", { maxChars: 10 }).length, 0);
  assert.ok(JSON.stringify(recallMemories(items, "问题")).length <= 3000);
});
test("a proposal without kind/scope defaults to background/global and is not globally recalled", async (t) => {
  const workspace = await fs.mkdtemp(path.join(os.tmpdir(), "syno-memory-default-"));
  t.after(() => fs.rm(workspace, { recursive: true, force: true }));
  const opsRoot = path.join(workspace, "ops"), store = new MemoryStore({ opsRoot });
  let message = "source";
  const op = (name, payload) => executeDomainOperation(name, payload, { workspace, job: { ownerKey: "owner", request: { sourceMessageId: message } }, clock: () => new Date("2026-10-18T23:59:00Z") });
  const first = (await op("memory.proposals.create", { statement: "使用中文回答" })).record;
  assert.equal(first.kind, "background", "未指定 kind 时安全默认 background");
  assert.equal(first.scope, "global", "未指定 scope 时安全默认 global");
  message = "confirm";
  await op("memory.promote", { id: first.id, version: recordVersion(first), confirmationMessageId: message });
  assert.deepEqual(await store.search("owner", "你好"), [], "background 不能像全局偏好一样每轮注入");
});

test("propose/confirm/correct/replace/forget stays isolated and versioned across reload", async (t) => {
  const workspace = await fs.mkdtemp(path.join(os.tmpdir(), "syno-memory-中文-"));
  t.after(() => fs.rm(workspace, { recursive: true, force: true }));
  const opsRoot = path.join(workspace, "ops"), store = new MemoryStore({ opsRoot });
  let message = "source";
  const op = (name, payload) => executeDomainOperation(name, payload, { workspace, job: { ownerKey: "owner", request: { sourceMessageId: message } }, clock: () => new Date("2026-10-18T23:59:00Z") });
  const first = (await op("memory.proposals.create", { statement: "使用中文回答", kind: "preference", scope: "global" })).record;
  assert.equal((await store.search("owner", "你好")).length, 0);
  await assert.rejects(op("memory.promote", { id: first.id, version: recordVersion(first), confirmationMessageId: message }));
  message = "confirm";
  const active = (await op("memory.promote", { id: first.id, version: recordVersion(first), confirmationMessageId: message })).record;
  assert.equal((await store.search("owner", "你好"))[0].statement, "使用中文回答");
  message = "correct";
  const candidate = (await op("memory.proposals.correct", { id: first.id, version: recordVersion(active), statement: "使用英文回答" })).record;
  assert.equal((await store.search("owner", "你好"))[0].id, first.id);
  const replacement = (await op("memory.promote", { id: candidate.id, version: recordVersion(candidate), confirmationMessageId: "confirm-new" })).record;
  assert.deepEqual((await store.search("owner", "你好")).map(r => r.id), [replacement.id]);
  assert.equal((await store.get("owner", first.id)).statement, undefined);
  await assert.rejects(store.get("stranger", replacement.id), { code: "DOMAIN_RECORD_NOT_FOUND" });
  const forgotten = (await op("memory.forget", { id: replacement.id, version: recordVersion(replacement) })).record;
  assert.equal(forgotten.statement, undefined);
  assert.deepEqual(await new MemoryStore({ opsRoot }).search("owner", "你好"), []);
  assert.equal((await store.get("owner", replacement.id)).statement, undefined);
  await assert.rejects(fs.access(path.join(workspace, "vault")), { code: "ENOENT" });
  const records = await listDomainRecords(opsRoot, "memory", "owner");
  assert.ok(records.every(r => r.file.includes(path.join("2026", "10"))));
  assert.match(first.id, /^memory-20261019-/);
});
